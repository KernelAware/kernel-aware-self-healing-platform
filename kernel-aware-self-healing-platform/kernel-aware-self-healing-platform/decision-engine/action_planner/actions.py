from action_planner.send_decisions.backend import notify_backend, save_incident
from action_planner.send_decisions.healing_engine import send_to_healing_engine
import uuid


operator_map = {
    "Greater Than (>)": ">",
    "Less Than (<)": "<",
    "Greater Than or Equal (>=)": ">=",
    "Less Than or Equal (<=)": "<=",
    "Equal (=)": "=",
    "Not Equal (!=)": "!="
}


cpu_alert_names = {
    "cpu_usage_percent": "High CPU Utilization Detected",
    "cpu_load_1min": "High 1-Minute Load Average Detected",
    "cpu_core_usage_percent": "High Per-Core CPU Utilization Detected",
    "cpu_load_5min": "High 5-Minute Load Average Detected",
    "cpu_load_15min": "High 15-Minute Load Average Detected",
    "cpu_freq_current_mhz": "Abnormal CPU Frequency Detected",
    "cpu_times_user": "High CPU User Time Detected",
    "cpu_times_system": "High CPU System Time Detected",
    "cpu_times_iowait": "High CPU I/O Wait Detected",
    "cpu_times_steal": "High CPU Steal Time Detected",
    "cpu_ctx_switches": "High Context Switch Rate Detected",
}


def create_action_plan(decision, incident, rules, policy):

    incident_detail, alert = create_alert(
        decision,
        incident,
        rules,
        policy
    )

    monitor_type = (
        incident.get("monitor_type")
        or incident.get("incident_type")
        or ""
    ).lower()

    # Handle blocked policies.
    if not policy.get("allowed", False):

        if policy.get("reason") != "Rule is disabled":
            notify_backend(incident_detail, alert)
            save_incident(incident_detail)

        return {
            "status": "BLOCKED",
            "reason": policy.get("reason", "Policy blocked the action")
        }

    # Notify the backend about the incident.
    notify_backend(incident_detail, alert)

    # Disk incidents are alert-only.
    # They must not trigger healing actions.
    if monitor_type == "disk":
        return {
            "status": "ALERT_ONLY",
            "reason": "Disk incidents are handled through alert and recovery conditions.",
            "incident_id": incident_detail["incident_id"]
        }

    action_types = (
        decision.get("actions")
        or decision.get("all_actions")
        or policy.get("actions", [])
    )

    if not action_types:
        return {
            "status": "NO_ACTION",
            "reason": decision.get("reason", "No action selected")
        }

    action_plan = {
        "action_id": f'action-{incident.get("rule_id")}',
        "type": action_types,
        "system_id": incident.get("system_id"),
        "target": incident.get("target"),
        "service": incident.get("target"),
        "pid": incident.get("pid"),
    }

    send_to_healing_engine(action_plan)

    return {
        "status": "SENT",
        "action_plan": action_plan
    }


def create_alert(decision, incident, rules, policy):

    # Preserve the incident ID generated by the Analytics Engine.
    # Generate a fallback only when one was not supplied.
    rule_id = incident.get("rule_id")

    incident_id = (
        incident.get("incident_id")
        or f"INC-{uuid.uuid4().hex[:8].upper()}"
    )

    system = incident.get("system_id", "Unknown")
    target = incident.get("target", "Unknown")
    pid = incident.get("pid")

    incident_type = (
        incident.get("monitor_type")
        or incident.get("incident_type")
        or ""
    ).lower()

    violated_metric = incident.get("violated_metric") or {}

    metric = violated_metric.get("metric", "Unknown")
    current_value = incident.get("value", 0)
    threshold = violated_metric.get("threshold")
    operator = violated_metric.get("operator")
    duration = violated_metric.get("duration_seconds", 0)

    severity = incident.get(
        "severity",
        incident.get("incident_severity", "Warning")
    )

    priority = incident.get(
        "incident_priority",
        incident.get("priority", "P2")
    )


    priority = incident.get(
        "incident_priority",
        incident.get("priority", "P2")
    )

    normalized_operator = operator_map.get(operator, operator)

    # Default alert title and description for all monitoring categories.
    title = f"{metric} - {target}"

    comparison = {
        ">": "above",
        "<": "below",
        ">=": "at or above",
        "<=": "at or below",
        "=": "equal to",
        "!=": "not equal to",
    }.get(normalized_operator, normalized_operator)

    duration_seconds = int(duration or 0)
    duration_text = format_duration(duration_seconds)

    alert_body = (
        f"{metric} reached {current_value}, "
        f"{comparison} threshold {threshold} "
        f"for {duration_text}."
    )

    # CPU-specific alert titles.
    if incident_type == "cpu":

        title = cpu_alert_names.get(
            metric,
            f"High {metric.replace('_', ' ').title()} Detected"
        )

    recommended_action = decision.get(
        "Selected_action",
        "No Decision"
    )

    decision_type = decision.get(
        "decision",
        "NO_ACTION"
    )

    decision_reason = decision.get(
        "reason",
        "No reason provided"
    )

    configured_actions = rules.get("actions", [])

    automatic_execution = bool(
        configured_actions
        and configured_actions[0].get(
            "automatic_execution",
            False
        )
    )

    approval_required = (
        policy.get("reason") == "Approval required"
    )

    if automatic_execution and not approval_required:
        status = "HEALING"
        operator_required = False

    elif approval_required:
        status = "WAITING_APPROVAL"
        operator_required = True

    else:
        status = "OPEN"
        operator_required = False

    allowed_actions = [
        action
        for action in configured_actions
    ]

    incident_detail = {

        "id": incident_id,
        "incident_id": incident_id,
        "rule_id": rule_id,

        "monitor_type": incident.get(
            "monitor_type"
        ) or incident.get("incident_type"),

        "system_id": system,
        "target": target,

        "title": title,
        "monitor-type": incident_type,

        "priority": priority,
        "severity": severity,

        "system": (
            f"server-{int(system):02d}"
            if str(system).isdigit()
            else str(system)
        ),

        "process": target,
        "pid": pid,

        "detectedAgo": "now",

        "trigger": {
            "metric": metric,
            "currentValue": round(float(current_value or 0), 1),
            "operator": normalized_operator,
            "threshold": threshold,
            "duration": duration_text
        },

        "decision": {
            "recommendedAction": recommended_action,
            "decision": decision_type,
            "reason": decision_reason
        },

        "policy": {
            "ruleEnabled": rules.get(
                "rule", {}
            ).get("status", True),

            "automaticExecution": automatic_execution,
            "approvalRequired": approval_required,
            "cooldownPassed": policy.get(
                "cooldown_passed", False
            )
        },

        "rootCause": {
            "verified": incident.get(
                "root_cause_verified", False
            ),

            "source": incident.get(
                "root_cause_source",
                "System Telemetry"
            ),

            "traceId": incident.get("trace_id"),

            "traceName": incident.get(
                "trace_name",
                "Unknown"
            ),

            "timeline": incident.get("timeline", [])
        },

        "operatorAction": {
            "required": operator_required,

            "message": (
                "Review the recommendation and select an approved remediation action."
                if operator_required
                else "Automatic remediation is allowed by policy."
            ),

            "recommendedAction": recommended_action,
            "allowedActions": allowed_actions,
            "selectedAction": recommended_action,
            "reason": decision_reason
        },

        "status": status
    }

    tone_map = {
        "Critical": "danger",
        "High": "warning",
        "Medium": "muted",
        "Low": "muted",
        "WARNING": "warning",
        "CRITICAL": "danger",
        "INFO": "muted"
    }

    alert = {

        "id": incident_id,
        "incident_id": incident_id,
        "rule_id": rule_id,

        "monitor_type": incident.get(
            "monitor_type"
        ) or incident.get("incident_type"),

        "system_id": system,
        "target": target,

        "metric": metric,
        "current_value": current_value,
        "threshold": threshold,
        "operator": normalized_operator,

        "severity": severity,
        "priority": priority,

        "level": f"{priority} - {severity}",

        "tone": tone_map.get(
            severity,
            tone_map.get(str(severity).upper(), "muted")
        ),

        "age": "now",
        "title": title,
        "body": alert_body,

        "acked": False,
        "status": status,

        "system": system,
        "process": target,
        "pid": pid
    }

    return incident_detail, alert


def format_duration(seconds):

    seconds = int(seconds or 0)

    if seconds < 60:
        return f"{seconds} seconds"

    if seconds < 3600:
        minutes = seconds / 60
        return f"{minutes:.1f} minutes"

    hours = seconds / 3600
    return f"{hours:.1f} hours"