-- Kernel-Aware Self-Healing Platform
-- PostgreSQL schema for database: kernelproject_database
-- Run this script while phpPgAdmin is connected to kernelproject_database.
-- It is safe to run more than once: it does not drop existing data.

BEGIN;

CREATE TABLE IF NOT EXISTS systems (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostname     VARCHAR(255) NOT NULL,
    ip_address   VARCHAR(45),
    os_name      VARCHAR(100),
    os_version   VARCHAR(100),
    architecture VARCHAR(50),
    environment  VARCHAR(50),
    status       VARCHAR(30) DEFAULT 'active',
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id    BIGINT REFERENCES systems(id) ON DELETE SET NULL,
    name         VARCHAR(100) NOT NULL,
    status       VARCHAR(20) DEFAULT 'ENABLED',
    priority     VARCHAR(20) DEFAULT 'Medium',
    severity     VARCHAR(20) DEFAULT 'Warning',
    owner        VARCHAR(100),
    environment  VARCHAR(100),
    region       VARCHAR(100),
    monitor_type VARCHAR(30) NOT NULL,
    target_type  VARCHAR(30),
    target       VARCHAR(30),
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rule_targets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id     BIGINT NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
    target_type VARCHAR(30) NOT NULL,
    target      VARCHAR(100) NOT NULL,
    host        VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS rule_metrics (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id          BIGINT NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
    metric           VARCHAR(150) NOT NULL,
    operator         VARCHAR(30),
    threshold        DOUBLE PRECISION,
    duration_seconds INTEGER DEFAULT 0,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rule_actions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id              BIGINT NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
    action_type          VARCHAR(50) NOT NULL,
    action_script        TEXT,
    automatic_execution  BOOLEAN DEFAULT FALSE,
    approval_required    VARCHAR(30) DEFAULT 'ALWAYS',
    allowed_during       VARCHAR(40) DEFAULT 'ALWAYS',
    max_retry_attempts   INTEGER DEFAULT 0,
    cooldown_seconds     INTEGER DEFAULT 0,
    suppress_duplicates  BOOLEAN DEFAULT TRUE,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rule_notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id     BIGINT NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
    event_type  VARCHAR(50) NOT NULL,
    channel     VARCHAR(30) NOT NULL,
    recipient   VARCHAR(255),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rule_recovery (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id                   BIGINT NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
    verification_required     BOOLEAN DEFAULT TRUE,
    metric                    VARCHAR(150),
    operator                  VARCHAR(30),
    "RECOVERY_threshold"     DOUBLE PRECISION,
    "RECOVERY_duration_seconds" INTEGER DEFAULT 0,
    created_at                TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rule_jira_configs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id              BIGINT NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
    site_url              VARCHAR(255) NOT NULL,
    account_email        VARCHAR(255) NOT NULL,
    api_token_encrypted  VARCHAR(1000) NOT NULL,
    project_key          VARCHAR(50) NOT NULL,
    issue_type           VARCHAR(50) NOT NULL,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_rule_jira_configs_rule_id UNIQUE (rule_id)
);

CREATE TABLE IF NOT EXISTS rule_servicenow_configs (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id                BIGINT NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
    instance_url            VARCHAR(255) NOT NULL,
    client_id               VARCHAR(255) NOT NULL,
    client_secret_encrypted VARCHAR(1000) NOT NULL,
    created_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_rule_servicenow_configs_rule_id UNIQUE (rule_id)
);

CREATE TABLE IF NOT EXISTS incidents (
    id          VARCHAR(40) PRIMARY KEY,
    rule_id     INTEGER,
    system_id   INTEGER NOT NULL,
    category    VARCHAR(30) NOT NULL,
    target      VARCHAR(255) NOT NULL,
    metric      VARCHAR(150) NOT NULL,
    severity    VARCHAR(30) NOT NULL,
    priority    VARCHAR(30) NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    opened_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP WITH TIME ZONE,
    detail      JSON NOT NULL DEFAULT '{}'::json,
    alert       JSON NOT NULL DEFAULT '{}'::json,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alert_incidents (
    incident_id    VARCHAR(64) PRIMARY KEY,
    fingerprint    VARCHAR(64) NOT NULL,
    system_id      BIGINT,
    rule_id        BIGINT,
    monitor_type   VARCHAR(30) NOT NULL,
    target_type    VARCHAR(30),
    target         VARCHAR(255),
    metric         VARCHAR(150),
    current_value  DOUBLE PRECISION,
    threshold      DOUBLE PRECISION,
    operator       VARCHAR(30),
    severity       VARCHAR(30),
    priority       VARCHAR(30),
    status         VARCHAR(30) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at    TIMESTAMP WITH TIME ZONE,
    incident_detail JSON NOT NULL,
    alert_payload  JSON
);

-- Indexes used by the backend and analytics engine.
CREATE INDEX IF NOT EXISTS ix_rules_system_id ON rules(system_id);
CREATE INDEX IF NOT EXISTS ix_rule_targets_rule_id ON rule_targets(rule_id);
CREATE INDEX IF NOT EXISTS ix_rule_metrics_rule_id ON rule_metrics(rule_id);
CREATE INDEX IF NOT EXISTS ix_rule_actions_rule_id ON rule_actions(rule_id);
CREATE INDEX IF NOT EXISTS ix_rule_notifications_rule_id ON rule_notifications(rule_id);
CREATE INDEX IF NOT EXISTS ix_rule_recovery_rule_id ON rule_recovery(rule_id);
CREATE INDEX IF NOT EXISTS ix_incidents_system_id ON incidents(system_id);
CREATE INDEX IF NOT EXISTS ix_incidents_status ON incidents(status);
CREATE INDEX IF NOT EXISTS ix_alert_incidents_fingerprint ON alert_incidents(fingerprint);
CREATE INDEX IF NOT EXISTS ix_alert_incidents_system_id ON alert_incidents(system_id);
CREATE INDEX IF NOT EXISTS ix_alert_incidents_rule_id ON alert_incidents(rule_id);
CREATE INDEX IF NOT EXISTS ix_alert_incidents_monitor_type ON alert_incidents(monitor_type);
CREATE INDEX IF NOT EXISTS ix_alert_incidents_status ON alert_incidents(status);

-- The application defaults to KAISP_SYSTEM_ID=1.
INSERT INTO systems (id, hostname, status)
VALUES (1, 'localhost', 'active')
ON CONFLICT (id) DO NOTHING;

-- Keep identity generation valid after the explicit starter row above.
SELECT setval(
    pg_get_serial_sequence('systems', 'id'),
    GREATEST((SELECT COALESCE(MAX(id), 1) FROM systems), 1),
    true
);

COMMIT;

